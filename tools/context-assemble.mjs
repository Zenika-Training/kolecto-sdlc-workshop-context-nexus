#!/usr/bin/env node
// context-assemble · simulates the Context Assembler: builds the context an agent reads for one squad's task.
// No dependency (Node 20+). Used by the starters (npm run context, gate) and by the devcontainer.
//
//   node tools/context-assemble.mjs --squad squad-a-policy                  # print the brief and the pin report
//   node tools/context-assemble.mjs --squad squad-a-policy --out ../starter/.context/brief.md
//   node tools/context-assemble.mjs --squad squad-a-policy --mark-stale     # flag the squad's outdated artefacts as stale
//   node tools/context-assemble.mjs --squad squad-a-policy --check          # exit 1 if anything is stale (used by gates)
//   node tools/context-assemble.mjs --all [--mark-stale]                    # facilitator view of the whole Nexus

import { writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, dirname, resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { DEFAULT_NEXUS, loadNexus, squadOf, checkPins, setStatus } from './lib/nexus.mjs';

function parseArgs(argv) {
  const args = { squad: null, out: null, markStale: false, check: false, all: false, nexus: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--squad') args.squad = argv[++i];
    else if (a === '--out') args.out = argv[++i];
    else if (a === '--nexus') args.nexus = argv[++i];
    else if (a === '--mark-stale') args.markStale = true;
    else if (a === '--check') args.check = true;
    else if (a === '--all') args.all = true;
    else if (a === '--help' || a === '-h') args.help = true;
  }
  return args;
}

// A contract that declares an exception to a higher level is only visible once someone approved it.
function contractAdmission(a) {
  if (a.meta.register !== 'contracts' || !a.meta['exception-to']) return 'ok';
  return a.meta['exception-approved-by'] ? 'exception-approved' : 'exception-pending';
}

function assemble(squad, artifacts) {
  const own = [...artifacts.values()].filter(a => squadOf(a.path) === squad);
  if (own.length === 0) throw new Error(`No artefact for squad "${squad}" in teams/`);

  const systemPrompt = [...artifacts.values()].filter(a =>
    a.meta['consumption-mode'] === 'system-prompt' && (!squadOf(a.path) || squadOf(a.path) === squad));
  const consumed = new Map();
  for (const a of own) for (const ref of a.meta.consumes || []) {
    const [path, pinned] = ref.split('@');
    if (squadOf(path) !== squad) consumed.set(path, pinned);
  }
  // `rag` artefacts are never inlined, even when consumed: they are listed, to be read on demand.
  const isRag = a => a.meta['consumption-mode'] === 'rag';
  const rag = [...artifacts.values()].filter(a => isRag(a) && (!squadOf(a.path) || consumed.has(a.path)));
  const injected = [
    ...own.filter(a => !['system-prompt', 'rag'].includes(a.meta['consumption-mode'])),
    ...[...consumed.keys()].map(p => artifacts.get(p)).filter(Boolean).filter(a => !systemPrompt.includes(a) && !isRag(a)),
    // The programme's mission context (brief, rules, decisions) is injected from Discover on,
    // before the squad has written anything: it is the first thing the agent must know.
    ...[...artifacts.values()].filter(a => a.meta.register === 'knowledge' && a.meta.level === 'programme' && a.meta['consumption-mode'] === 'context-injection'),
  ].filter((a, i, all) => all.indexOf(a) === i);
  const excluded = [];
  const keep = list => list.filter(a => {
    if (contractAdmission(a) === 'exception-pending') { excluded.push(a); return false; }
    return true;
  });

  const brief = {
    systemPrompt: keep(systemPrompt),
    injected: keep(injected),
    rag,
    excluded,
    pins: own.map(a => ({ a, issues: checkPins(a, artifacts) })),
  };
  const fingerprint = [...brief.systemPrompt, ...brief.injected].map(a => `${a.path}@${a.meta.version}`).sort().join('\n');
  brief.id = `TB-${squad}-${createHash('sha1').update(fingerprint).digest('hex').slice(0, 8)}`;
  return brief;
}

function renderBriefFile(squad, brief) {
  const section = (title, list) => list.length === 0 ? '' :
    `\n## ${title}\n\n` + list.map(a =>
      `<!-- ${a.path} · v${a.meta.version} · ${a.meta.status} -->\n${a.body.trim()}\n`).join('\n---\n\n');
  return `# Task brief ${brief.id}

> Generated by context-assemble on ${new Date().toISOString()} for **${squad}**. Do not edit by hand: regenerate it.
> The versions below are those of the Context Nexus at assembly time.
${brief.pins.some(p => p.issues.length) ? '\n> ⚠️ Some dependencies changed since they were pinned: see the context-assemble output.\n' : ''}
${section('Rules and contracts that always apply (system prompt)', brief.systemPrompt)}
${section('Mission context (context injection)', brief.injected)}
## Knowledge to look up on demand (simulated RAG)

${brief.rag.map(a => `- \`../context-nexus/${a.path}\` (v${a.meta.version})`).join('\n')}
`;
}

function printBrief(squad, brief) {
  const line = a => `    - ${a.path}@${a.meta.version}  [${a.meta.status}]`;
  console.log(`task_brief:\n  id: ${brief.id}\n  squad: ${squad}`);
  console.log(`  system_prompt:\n${brief.systemPrompt.map(line).join('\n')}`);
  console.log(`  context_injection:\n${brief.injected.map(line).join('\n')}`);
  console.log(`  rag:\n${brief.rag.map(line).join('\n')}`);
  if (brief.excluded.length) console.log(`  excluded (exception not approved):\n${brief.excluded.map(line).join('\n')}`);
}

function reportPins(pinsList) {
  let stale = 0;
  for (const { a, issues } of pinsList) {
    if (issues.length === 0) continue;
    stale++;
    console.log(`\n✗ ${a.path} (v${a.meta.version}, ${a.meta.status}) depends on versions that changed:`);
    for (const i of issues) console.log(`    ${i.kind.padEnd(14)} ${i.path}  pinned ${i.pinned} → current ${i.current ?? '—'}`);
  }
  if (stale === 0) console.log('\n✓ Every pinned dependency is up to date.');
  return stale;
}

function markStale(pinsList, hint) {
  for (const { a, issues } of pinsList)
    if (issues.length && ['active', 'draft'].includes(a.meta.status)) {
      setStatus(a, 'stale');
      console.log(`  → ${a.path} is now stale${hint ? `: ${hint}` : ''}`);
    }
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help || (!args.squad && !args.all)) {
    console.log('Usage: node tools/context-assemble.mjs --squad <squad> [--out <file>] [--mark-stale] [--check] [--nexus <dir>]\n' +
                '       node tools/context-assemble.mjs --all [--mark-stale] [--check]');
    process.exit(args.help ? 0 : 2);
  }
  const root = resolve(args.nexus || DEFAULT_NEXUS);
  const artifacts = loadNexus(root);

  if (args.all) {
    const pins = [...artifacts.values()].map(a => ({ a, issues: checkPins(a, artifacts) }));
    const stale = reportPins(pins);
    if (args.markStale) markStale(pins);
    process.exit(args.check && stale ? 1 : 0);
  }

  const brief = assemble(args.squad, artifacts);
  printBrief(args.squad, brief);
  const stale = reportPins(brief.pins);
  if (args.markStale) markStale(brief.pins, 'read the change, update the artefact and its pin, then set it back to active');

  const ownStale = brief.pins.filter(p => p.a.meta.status === 'stale').length;
  const out = args.out || join(root, '.context', `${args.squad}.md`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, renderBriefFile(args.squad, brief));
  console.log(`\nBrief written to ${relative(process.cwd(), out) || out}`);

  if (args.check && (stale || ownStale)) {
    console.log('\nCHECK: no-go, some artefacts are stale or pinned to an outdated version.');
    process.exit(1);
  }
}

main();
